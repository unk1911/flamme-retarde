def call_model(prompt: str, source: Path | None, tries: int = 3) -> bytes:
    parts: list[dict] = [{"text": STYLE + prompt}]
    if source is not None:
        mime = "image/png" if source.suffix.lower() == ".png" else "image/jpeg"
        parts.append({"inline_data": {
            "mime_type": mime,
            "data": base64.b64encode(source.read_bytes()).decode(),
        }})

    body = json.dumps({
        "contents": [{"parts": parts}],
        "generationConfig": {"imageConfig": {"aspectRatio": "16:9"}},
    }).encode()

    key = os.environ.get("GEMINI_API_KEY")
    if not key:
        sys.exit("error: GEMINI_API_KEY is not set")

    last = ""
    for attempt in range(tries):
        req = urllib.request.Request(
            ENDPOINT % MODEL, data=body,
            headers={"content-type": "application/json", "x-goog-api-key": key})
        try:
            with urllib.request.urlopen(req, timeout=180) as r:
                d = json.load(r)
        except urllib.error.HTTPError as e:
            last = "HTTP %s %s" % (e.code, e.read()[:200].decode("utf8", "replace"))
            time.sleep(3 + attempt * 4)
            continue
        except Exception as e:                       # noqa: BLE001
            last = str(e)
            time.sleep(3 + attempt * 4)
            continue

        cands = d.get("candidates") or []
        for c in cands:
            for p in c.get("content", {}).get("parts", []):
                if "inlineData" in p:
                    return base64.b64decode(p["inlineData"]["data"])
        # A refusal or a text-only answer: worth seeing rather than swallowing.
        txt = " ".join(p.get("text", "") for c in cands
                       for p in c.get("content", {}).get("parts", []))
        last = "no image returned. %s" % (txt[:200] or json.dumps(d)[:200])
        time.sleep(2)
    raise RuntimeError(last)


def to_payload(raw: Path, dest: Path, width=1280, height=720):
    """Crop to 16:9 and write the WebP the build inlines."""
    im = Image.open(raw).convert("RGB")
    want = width / height
    have = im.width / im.height
    if have > want:
        w = int(im.height * want)
        im = im.crop(((im.width - w) // 2, 0, (im.width - w) // 2 + w, im.height))
    elif have < want:
        h = int(im.width / want)
        im = im.crop((0, (im.height - h) // 2, im.width, (im.height - h) // 2 + h))
    im = im.resize((width, height), Image.LANCZOS)
    dest.parent.mkdir(parents=True, exist_ok=True)
    im.save(dest, "WEBP", quality=82, method=6)
    return dest.stat().st_size


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--repack", action="store_true",
                    help="skip the model, just rebuild the WebPs from refs/panels")
    args = ap.parse_args()

    PANELS.mkdir(parents=True, exist_ok=True)
    print("panels via %s" % MODEL)

    for key, ref, prompt in PANELS_SPEC:
        if args.only and key not in args.only:
            continue
        raw = PANELS / ("%s.png" % key)
        dest = OUT / ("panel_%s.webp" % key)

        if not raw.exists() or (args.force and not args.repack):
            if args.repack:
                print("  %-11s missing raw, skipped" % key)
                continue
            src = None
            if ref:
                src = REFS / ref
                if not src.exists():
                    print("  %-11s ref missing: %s" % (key, ref))
                    src = None
            try:
                data = call_model(prompt, src)
            except Exception as e:                   # noqa: BLE001
                print("  %-11s FAILED  %s" % (key, e))
                continue
            raw.write_bytes(data)

        size = to_payload(raw, dest)
        print("  %-11s %5.0f KB  %s" % (key, size / 1024,
                                        ("from " + ref) if ref else "painted"))


if __name__ == "__main__":
    main()
