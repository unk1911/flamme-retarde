"""Generate the painted panels that run under the cinematic intro.

    export GEMINI_API_KEY=...
    python3 tools/gen_panels.py            # only what is missing
    python3 tools/gen_panels.py --force    # all of them again
    python3 tools/gen_panels.py --only war today

Calls Gemini 2.5 Flash Image ("nano banana"). Several panels are image-to-image
from the photographs in refs/, so the town in the painting is the actual town
and the aircraft is the actual aircraft; the rest are painted from the prompt.

Raw returns are kept in refs/panels/ so a good one is never regenerated by
accident. The build copies are 1280x720 WebP in build/payload/, which is what
gets inlined.

On style: the brief was "Ghibli-ish". These prompts describe the aesthetic —
hand-painted anime film backgrounds, gouache, warm Mediterranean light —
rather than naming a studio. It gets the same look and it is a better prompt.
"""

